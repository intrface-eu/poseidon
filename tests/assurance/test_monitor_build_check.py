"""Source-only parser/checker regressions with explicitly synthetic evidence.

All ELF/bin/sdkconfig files, compiler logs and vendor outputs below are invented
fixtures, not native builds, target execution, persistence or field evidence.
Only bounded Python fixture processes run in the subprocess tests; no toolchain,
compiler, device, network, radio or sensor is used.
"""
