class PriorHandlerRaised(RuntimeError):
    """Safe sentinel: a broken cancellation regression must not kill unittest."""


class SyntheticCancellationTests(unittest.TestCase):
    """Real OS signals and mocked delivery, with independently owned cleanup."""

    def setUp(self) -> None:
        self.previous = {sig: signal.getsignal(sig) for sig in checker.INSPECTION_SIGNALS}
        self.previous_mask = signal.pthread_sigmask(signal.SIG_BLOCK, set())
        self.real_popen = subprocess.Popen
        self.real_killpg = os.killpg
        self.real_signal = signal.signal
        self.spawned = []
        self.on_spawn = None
        self.prior_deliveries = []

        def prior_handler(signum: int, _frame: object) -> None:
            self.prior_deliveries.append(signum)
            raise PriorHandlerRaised(f"previous handler received {signum}")

        self.prior_handler = prior_handler
        self.addCleanup(self.cleanup_owned)
        for sig in checker.INSPECTION_SIGNALS:
            signal.signal(sig, self.prior_handler)
        self.spawn_patch = patch.object(checker.subprocess, "Popen", side_effect=self.capture_spawn)
        self.spawn_patch.start()
        self.addCleanup(self.spawn_patch.stop)

    def capture_spawn(self, *args, **kwargs):
        process = self.real_popen(*args, **kwargs)
        # Test ownership is recorded BEFORE injecting the production spawn gap.
        # Even a broken checker cannot leave our Python fixture running.
        self.spawned.append(process)
        if self.on_spawn is not None:
            self.on_spawn(process)
        return process

    def cleanup_owned(self) -> None:
        signal.pthread_sigmask(signal.SIG_BLOCK, checker.INSPECTION_SIGNALS)
        try:
            for process in self.spawned:
                try:
                    self.real_killpg(process.pid, signal.SIGKILL)
                except ProcessLookupError:
                    pass
                finally:
                    if process.stdout is not None:
                        process.stdout.close()
                    process.wait(timeout=5)
        finally:
            for sig, handler in self.previous.items():
                self.real_signal(sig, handler)
            signal.pthread_sigmask(signal.SIG_SETMASK, self.previous_mask)

    def assert_restored_and_reaped(self) -> None:
        self.assertEqual(signal.pthread_sigmask(signal.SIG_BLOCK, set()), self.previous_mask)
        for sig in checker.INSPECTION_SIGNALS:
            self.assertIs(signal.getsignal(sig), self.prior_handler)
        for process in self.spawned:
            self.assertIsNotNone(process.returncode)
            with self.assertRaises(ProcessLookupError):
                self.real_killpg(process.pid, 0)

    @staticmethod
    def deliver(signum: int, actual: bool) -> None:
        if actual:
            os.kill(os.getpid(), signum)
        else:
            signal.getsignal(signum)(signum, None)

    @staticmethod
    def sleeping_fixture() -> list[str]:
        return [sys.executable, "-c", "import time; time.sleep(60)"]

    def active_cancellation(self, actual: bool) -> None:
        for signum in checker.INSPECTION_SIGNALS:
            with self.subTest(signum=signum):
                def deliver(_timeout: float) -> list:
                    self.deliver(signum, actual)
                    return []
                with patch.object(checker.selectors.DefaultSelector, "select", side_effect=deliver):
                    with self.assertRaises(checker.InspectionInterrupted) as caught:
                        checker.run_tool(self.sleeping_fixture())
                self.assertEqual(caught.exception.signum, signum)
                self.assert_restored_and_reaped()
        self.assertEqual(self.prior_deliveries, [])

    def test_actual_sigint_and_sigterm_during_inspection_reap_group(self) -> None:
        self.active_cancellation(actual=True)

    def test_mocked_sigint_and_sigterm_during_inspection_reap_group(self) -> None:
        self.active_cancellation(actual=False)

    def spawn_gap_cancellation(self, actual: bool) -> None:
        for signum in checker.INSPECTION_SIGNALS:
            with self.subTest(signum=signum):
                self.on_spawn = lambda _process: self.deliver(signum, actual)
                with self.assertRaises(checker.InspectionInterrupted) as caught:
                    checker.run_tool(self.sleeping_fixture())
                self.assertEqual(caught.exception.signum, signum)
                self.assert_restored_and_reaped()
        self.assertEqual(self.prior_deliveries, [])

    def test_actual_sigint_and_sigterm_in_spawn_registration_gap_are_deferred(self) -> None:
        self.spawn_gap_cancellation(actual=True)

    def test_mocked_sigint_and_sigterm_in_spawn_registration_gap_are_deferred(self) -> None:
        self.spawn_gap_cancellation(actual=False)

    def test_first_cancellation_is_preserved_when_both_signals_arrive_in_spawn_gap(self) -> None:
        def interrupt_twice(_process) -> None:
            self.deliver(signal.SIGTERM, actual=True)
            self.deliver(signal.SIGINT, actual=True)
        self.on_spawn = interrupt_twice
