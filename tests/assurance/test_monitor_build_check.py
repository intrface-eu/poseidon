def synthetic_elf() -> bytes:
    data = bytearray(256)
    data[:16] = b"\x7fELF\x01\x01\x01" + bytes(9)
    struct.pack_into("<HHIIIIIHHHHHH", data, 16, 2, 94, 1, 0x40081200, 52, 84, 0x300, 52, 32, 1, 40, 2, 1)
    data[200:] = b"SYNTHETIC ELF FIXTURE".ljust(56, b"!")
    return bytes(data)


def synthetic_nm() -> str:
    # Addresses are invented and carry no initializer/layout meaning.
    records = [f"{0x400D1000 + i * 16:08x} {'t' if 'worker_entry' in name else 'T'} {name}" for i, name in enumerate(checker.REQUIRED_TEXT_SYMBOLS)]
    return "\n".join(records + ["         U unrelated_synthetic_undefined", "3ffb0000 b synthetic_data"]) + "\n"


def synthetic_objdump(elf: Path) -> str:
    return f"\n{elf}:     file format elf32-xtensa-le\narchitecture: xtensa, flags 0x00000112:\nEXEC_P, HAS_SYMS, D_PAGED\nstart address 0x40081200\n\n"


def synthetic_disassembly(elf: Path, symbol: str) -> str:
    # Invented minimal body, intentionally identical for both profiles. Neither
    # these instructions nor their addresses establish monitor enabled state.
    return f"\n{elf}:     file format elf32-xtensa-le\n\nDisassembly of section .flash.text:\n\n400d1000 <{symbol}>:\n400d1000:\t004136\tentry\ta1, 32\n400d1003:\tf01d\tretw.n\n\n"


class SyntheticPairTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory(prefix="poseidon-synthetic-monitor-check-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        self.packages = self.root / "packages"
        self.toolchain = self.packages / checker.TOOLCHAIN
        (self.toolchain / "bin").mkdir(parents=True)
        (self.toolchain / "package.json").write_text(json.dumps({"name": checker.TOOLCHAIN, "version": checker.TOOLCHAIN_VERSION}))
        for name in ("nm", "objdump"):
            (self.toolchain / "bin" / f"xtensa-esp32-elf-{name}").write_bytes(b"SYNTHETIC NOT EXECUTABLE; vendor output is mocked")
        self.builds = {}
        self.logs = {}
        for profile in ("monitor_disabled", "monitor_persisted"):
            build = self.root / (profile + "-build")
            (build / profile).mkdir(parents=True)
            (build / profile / "firmware.elf").write_bytes(synthetic_elf())
            (build / profile / "firmware.bin").write_bytes(b"SYNTHETIC BIN " + profile.encode())
            (build / f"sdkconfig.{profile}").write_text("# SYNTHETIC SDKCONFIG, not generated by a build\n")
            self.builds[profile] = build
            self.logs[profile] = self.root / (profile + ".log")
            self.logs[profile].write_text(self.log_text(profile))
        self.nm_output = synthetic_nm()
        self.objdump_transform = lambda text: text
        self.disassembly_transform = lambda text, symbol: text
        self.tool_calls = []
        self.mock_tool = patch.object(checker, "run_tool", side_effect=self.fake_tool).start()
        self.addCleanup(patch.stopall)

    def command(self, profile: str) -> str:
        return f"xtensa-esp32-elf-g++ -o {self.builds[profile] / profile / 'src/main.cpp.o'} -c -std=gnu++17 -Og -Wall -fdata-sections -DPLATFORMIO=60118 -D{checker.MACRO}={int(profile == 'monitor_persisted')} -Isynthetic/include src/main.cpp"

    def log_text(self, profile: str) -> str:
        return f"SYNTHETIC VERBOSE BUILD LOG; no compiler was run\n{self.command(profile)}\n========================= [SUCCESS] Took 1.23 seconds =========================\n{profile} SUCCESS 00:00:01.234\n"

    def fake_tool(self, argv: list[str]) -> str:
        self.tool_calls.append(argv)
        if argv[1] == "-f":
            return self.objdump_transform(synthetic_objdump(Path(argv[2])))
        if argv[1] == "-d":
            self.assertEqual(len(argv), 4)
            self.assertTrue(argv[2].startswith("--disassemble="))
            symbol = argv[2].split("=", 1)[1]
            self.assertIn(symbol, checker.MANUAL_DISASSEMBLY_SYMBOLS.values())
            return self.disassembly_transform(synthetic_disassembly(Path(argv[3]), symbol), symbol)
        self.assertEqual(argv[1], "-C")
        return self.nm_output

    def pair(self) -> dict:
        return checker.check_pair(self.builds["monitor_disabled"], self.builds["monitor_persisted"], self.logs["monitor_disabled"], self.logs["monitor_persisted"], self.packages)

    def replace_log(self, old: str, new: str, profile: str = "monitor_disabled") -> None:
        log = self.logs[profile]
        log.write_text(log.read_text().replace(old, new))

    def artifact(self, name: str, profile: str = "monitor_disabled") -> Path:
        if name == "sdkconfig":
            return self.builds[profile] / f"sdkconfig.{profile}"
        return self.builds[profile] / profile / f"firmware.{name}"

    def test_synthetic_pair_accepts_flags_and_symbols_without_semantic_or_field_claim(self) -> None:
        report = self.pair()
        self.assertTrue(report["passed"])
        self.assertTrue(report["monitor_binaries_distinct"])
        self.assertFalse(report["release_authorized"])
        self.assertFalse(report["initializer_semantics_verified"])
        self.assertTrue(report["manual_initializer_review_required"])
        self.assertFalse(report["fresh_build_provenance_verified"])
        self.assertFalse(report["warning_free_claim"])
        self.assertEqual(len(report["profiles"]), 2)
        self.assertEqual(report["diagnostics_count"], 0)
        for profile in report["profiles"]:
            self.assertEqual(set(profile["defined_text_symbols"]), set(checker.REQUIRED_TEXT_SYMBOLS))
            self.assertEqual(len(profile["artifacts"]["bin"]["sha256"]), 64)
            self.assertFalse(profile["log"]["compile_commands_used"])
        self.assertEqual(len(self.tool_calls), 8)
        self.assertTrue(all(Path(call[0]).parent == self.toolchain / "bin" for call in self.tool_calls))

    def test_raw_manual_disassembly_is_retained_with_command_output_and_elf_hashes(self) -> None:
        report = self.pair()
        for profile in report["profiles"]:
            elf = Path(profile["artifacts"]["elf"]["path"])
            evidence = profile["manual_disassembly"]
            self.assertEqual(set(evidence), {"initializer", "app_main"})
            for name, symbol in checker.MANUAL_DISASSEMBLY_SYMBOLS.items():
                item = evidence[name]
                command = [str(self.toolchain / "bin/xtensa-esp32-elf-objdump"), "-d", f"--disassemble={symbol}", str(elf)]
                raw = synthetic_disassembly(elf, symbol)
                self.assertEqual(item["output"], raw)
                self.assertEqual(item["output_bytes"], len(raw.encode("utf-8")))
                self.assertEqual(item["output_sha256"], hashlib.sha256(raw.encode("utf-8")).hexdigest())
                self.assertEqual(item["command"], command)
                command_json = json.dumps(command, ensure_ascii=True, separators=(",", ":"))
                self.assertEqual(item["command_sha256"], hashlib.sha256(command_json.encode("utf-8")).hexdigest())
                self.assertEqual(item["elf_sha256"], profile["artifacts"]["elf"]["sha256"])
                self.assertFalse(item["semantics_verified"])
        self.assertFalse(report["initializer_semantics_verified"])
        self.assertTrue(report["manual_initializer_review_required"])

    def test_manual_disassembly_empty_and_size_limits_fail(self) -> None:
        for replacement in ("", "SYNTHETIC" * (checker.MAX_DISASSEMBLY_BYTES // 9 + 1)):
            with self.subTest(bytes=len(replacement)):
                self.disassembly_transform = lambda _text, _symbol: replacement
                with self.assertRaisesRegex(checker.CheckError, "disassembly.*size limit"):
                    self.pair()
        self.disassembly_transform = lambda text, _symbol: text
        with patch.object(checker, "MAX_DISASSEMBLY_BYTES", 16), self.assertRaisesRegex(checker.CheckError, "size limit"):
            self.pair()

    def test_missing_wrong_and_duplicate_manual_disassembly_frames_fail(self) -> None:
        for target in checker.MANUAL_DISASSEMBLY_SYMBOLS.values():
            for mutation in (lambda text: text.replace(f"<{target}>", "<synthetic_other_symbol>"), lambda text: text.replace("firmware.elf:", "wrong.elf:"), lambda text: text.replace("elf32-xtensa-le", "elf64-x86-64"), lambda text: text + f"400d2000 <{target}>:\n"):
                with self.subTest(target=target, mutation=mutation):
                    self.disassembly_transform = lambda text, symbol: mutation(text) if symbol == target else text
                    with self.assertRaisesRegex(checker.CheckError, "manual disassembly frame"):
                        self.pair()

    def test_elf_changed_during_manual_disassembly_is_rechecked_and_rejected(self) -> None:
        def mutate_during_disassembly(argv: list[str]) -> str:
            if argv[1] == "-d":
                path = self.artifact("elf")
                data = path.read_bytes()
                path.write_bytes(data[:200] + b"X" + data[201:])
            return self.fake_tool(argv)
        self.mock_tool.side_effect = mutate_during_disassembly
        with self.assertRaisesRegex(checker.CheckError, "artifact changed"):
            self.pair()
        self.assertTrue(any(argv[1] == "-d" for argv in self.tool_calls))

    def test_manual_disassembly_tool_failure_cannot_produce_passing_report(self) -> None:
        def fail_disassembly(argv: list[str]) -> str:
            if argv[1] == "-d":
                raise checker.CheckError("synthetic manual disassembly timeout")
            return self.fake_tool(argv)
        self.mock_tool.side_effect = fail_disassembly
